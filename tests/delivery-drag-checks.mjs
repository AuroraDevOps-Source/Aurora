import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const listeners = {}, calls = [];
const classes = new Set();
const destination = { dataset: { routeTruck: 'B' }, classList: { add: x => classes.add(x), remove: x => classes.delete(x) } };
const handle = { dataset: { dragOrder: 'ORDER-1', fromTruck: 'A' }, disabled: false, setPointerCapture() {} };
let underPointer = destination;
const grid = { addEventListener(type, fn) { assert.equal(listeners[type], undefined); listeners[type] = fn; }, contains: x => x === destination };
const context = { window: {}, console, document: { getElementById: () => grid, elementFromPoint: () => ({ closest: () => underPointer }) } };
vm.runInNewContext(fs.readFileSync('src/Aurora.Client/wwwroot/js/map.js', 'utf8'), context);
const receiver = { invokeMethodAsync: (...args) => { calls.push(args); return Promise.resolve(); } };
context.window.routeMap.initDeliveryDrag('grid', receiver);
context.window.routeMap.initDeliveryDrag('grid', receiver);
const fire = (type, args = {}) => listeners[type]({ target: { closest: () => handle }, button: 0, pointerId: 1, clientX: 10, clientY: 10, preventDefault() {}, ...args });
fire('pointerdown'); fire('pointerup'); assert.equal(calls.length, 0);
fire('pointerdown'); fire('pointermove', {clientX:100}); assert.equal(classes.has('delivery-drop-target'), true);
fire('pointerup'); assert.deepEqual(calls, [['MoveDelivery','ORDER-1','B']]); assert.equal(classes.size, 0);
fire('pointerdown'); fire('pointermove', {clientX:100}); fire('pointercancel'); fire('pointerup'); assert.equal(calls.length, 1);
fire('pointerdown'); fire('pointermove', {clientX:100}); fire('keydown', {key:'Escape'}); fire('pointerup'); assert.equal(calls.length, 1);
destination.dataset.routeTruck = 'A';
fire('pointerdown'); fire('pointermove', {clientX:100}); fire('pointerup'); assert.equal(calls.length, 1);
destination.dataset.routeTruck = 'B'; handle.disabled = true;
fire('pointerdown'); fire('pointermove', {clientX:100}); fire('pointerup'); assert.equal(calls.length, 1);
handle.disabled = false; underPointer = null;
fire('pointerdown'); fire('pointermove', {clientX:100}); fire('pointerup'); assert.equal(calls.length, 1);
console.log('PASS: delivery drag, click threshold, duplicate initialization, cancellation, Escape, same truck, disabled handle and outside drop.');
