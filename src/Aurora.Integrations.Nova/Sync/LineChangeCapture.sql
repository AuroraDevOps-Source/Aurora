SET TERM ^;
CREATE TRIGGER AURORA_SYNC_OPS_LINE_ITEMS FOR OPS_LINE_ITEMS
ACTIVE AFTER INSERT OR UPDATE OR DELETE POSITION 32760
AS
BEGIN
 IF(UPDATING OR DELETING) THEN
   EXECUTE PROCEDURE AURORA_CAPTURE_CHANGE('order-or-manifest',CAST(OLD.OPL_ORDER_ID AS VARCHAR(80)),'U');
 IF(INSERTING OR UPDATING) THEN
   EXECUTE PROCEDURE AURORA_CAPTURE_CHANGE('order-or-manifest',CAST(NEW.OPL_ORDER_ID AS VARCHAR(80)),'U');
END^
SET TERM ;^
