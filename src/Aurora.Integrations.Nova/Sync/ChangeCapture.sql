-- Install only on a Nova database explicitly connected for synchronization.
-- Run once with Firebird isql (SET TERM is an isql directive).
-- Queue rows participate in the original Nova business transaction. Never use
-- EVENT_ID as a high-water mark: generator values can commit out of order.
CREATE TABLE AURORA_SYNC_CONSUMER (
 CONSUMER_ID VARCHAR(36) NOT NULL PRIMARY KEY,
 ENABLED CHAR(1) DEFAULT 'N' NOT NULL CHECK(ENABLED IN ('Y','N')),
 BOOTSTRAPPED CHAR(1) DEFAULT 'N' NOT NULL CHECK(BOOTSTRAPPED IN ('Y','N'))
);
CREATE GENERATOR AURORA_SYNC_EVENT_GEN;
CREATE TABLE AURORA_SYNC_EVENT (
 EVENT_ID BIGINT NOT NULL PRIMARY KEY,
 CONSUMER_ID VARCHAR(36) NOT NULL,
 ENTITY_TYPE VARCHAR(30) NOT NULL,
 ENTITY_ID VARCHAR(80) NOT NULL,
 CHANGE_KIND CHAR(1) NOT NULL CHECK(CHANGE_KIND IN ('U','D')),
 CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 CONSTRAINT FK_AURORA_SYNC_CONSUMER FOREIGN KEY(CONSUMER_ID) REFERENCES AURORA_SYNC_CONSUMER(CONSUMER_ID)
);
CREATE INDEX IX_AURORA_SYNC_PENDING ON AURORA_SYNC_EVENT(CONSUMER_ID,EVENT_ID);
CREATE TABLE AURORA_SYNC_RECEIPT (
 CONSUMER_ID VARCHAR(36) NOT NULL,
 CHANGE_ID VARCHAR(36) NOT NULL,
 ENTITY_TYPE VARCHAR(30) NOT NULL,
 ENTITY_ID VARCHAR(80) NOT NULL,
 EXTERNAL_REVISION VARCHAR(128) NOT NULL,
 PAYLOAD_HASH VARCHAR(64) NOT NULL,
 CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 PRIMARY KEY(CONSUMER_ID,CHANGE_ID)
);
SET TERM ^;
CREATE PROCEDURE AURORA_CAPTURE_CHANGE(ENTITY_TYPE VARCHAR(30),ENTITY_ID VARCHAR(80),CHANGE_KIND CHAR(1))
AS DECLARE VARIABLE CONSUMER_ID VARCHAR(36);
BEGIN
 FOR SELECT C.CONSUMER_ID FROM AURORA_SYNC_CONSUMER C WHERE C.ENABLED='Y'
   AND C.CONSUMER_ID IS DISTINCT FROM RDB$GET_CONTEXT('USER_TRANSACTION','AURORA_SYNC_ORIGIN')
   INTO :CONSUMER_ID DO
 BEGIN
  INSERT INTO AURORA_SYNC_EVENT(EVENT_ID,CONSUMER_ID,ENTITY_TYPE,ENTITY_ID,CHANGE_KIND)
    VALUES(GEN_ID(AURORA_SYNC_EVENT_GEN,1),:CONSUMER_ID,:ENTITY_TYPE,:ENTITY_ID,:CHANGE_KIND);
 END
END^
CREATE PROCEDURE AURORA_CAPTURE_STOP_PARENT(STOP_ID BIGINT)
AS DECLARE VARIABLE PARENT_ID BIGINT;
BEGIN
 SELECT S.OPS_ORDER_ID FROM OPS_STOP_REC S WHERE S.OPS_STOP_ID=:STOP_ID INTO :PARENT_ID;
 IF(PARENT_ID IS NOT NULL) THEN EXECUTE PROCEDURE AURORA_CAPTURE_CHANGE('order-or-manifest',CAST(:PARENT_ID AS VARCHAR(80)),'U');
END^
CREATE TRIGGER AURORA_SYNC_EQUIP_HEADER FOR EQUIP_HEADER
ACTIVE AFTER INSERT OR UPDATE OR DELETE POSITION 32760
AS
BEGIN
 IF(DELETING) THEN EXECUTE PROCEDURE AURORA_CAPTURE_CHANGE('equipment',CAST(OLD.EH_ID AS VARCHAR(80)),'D');
 ELSE EXECUTE PROCEDURE AURORA_CAPTURE_CHANGE('equipment',CAST(NEW.EH_ID AS VARCHAR(80)),'U');
END^
