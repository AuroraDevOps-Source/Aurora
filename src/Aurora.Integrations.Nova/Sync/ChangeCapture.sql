CREATE TRIGGER AURORA_SYNC_OPS_STOP_REC FOR OPS_STOP_REC
ACTIVE AFTER INSERT OR UPDATE OR DELETE POSITION 32760
AS
BEGIN
 -- Capture the aggregate identity while it is still available. A deleted stop
 -- cannot be looked up later to discover its order/manifest.
 IF(UPDATING OR DELETING) THEN
   IF(OLD.OPS_ORDER_ID IS NOT NULL) THEN EXECUTE PROCEDURE AURORA_CAPTURE_CHANGE('order-or-manifest',CAST(OLD.OPS_ORDER_ID AS VARCHAR(80)),'U');
 IF(INSERTING OR UPDATING) THEN
   IF(NEW.OPS_ORDER_ID IS NOT NULL) THEN EXECUTE PROCEDURE AURORA_CAPTURE_CHANGE('order-or-manifest',CAST(NEW.OPS_ORDER_ID AS VARCHAR(80)),'U');
END^
CREATE TRIGGER AURORA_SYNC_OPS_MANIFEST_STO FOR OPS_MANIFEST_STOPS
ACTIVE AFTER INSERT OR UPDATE OR DELETE POSITION 32760
AS
BEGIN
 IF(UPDATING OR DELETING) THEN BEGIN
   EXECUTE PROCEDURE AURORA_CAPTURE_STOP_PARENT(OLD.OSM_STOP_ID);
   EXECUTE PROCEDURE AURORA_CAPTURE_STOP_PARENT(OLD.OSM_PKUP_DELV_ID);
 END
 IF(INSERTING OR UPDATING) THEN BEGIN
   EXECUTE PROCEDURE AURORA_CAPTURE_STOP_PARENT(NEW.OSM_STOP_ID);
   EXECUTE PROCEDURE AURORA_CAPTURE_STOP_PARENT(NEW.OSM_PKUP_DELV_ID);
 END
END^
SET TERM ;^
