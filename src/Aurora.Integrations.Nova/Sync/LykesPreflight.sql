-- READ-ONLY REVIEW QUERIES. Run on an approved restored tenant clone first.
-- This file performs no migration, adoption, enrollment, backfill or enablement.
-- MVP: no stable-ID column or Delphi patch is required. Metadata reports any
-- optional earlier schema without selecting from it.
SELECT TRIM(RDB$RELATION_NAME) AS RELATION_NAME
FROM RDB$RELATIONS
WHERE RDB$RELATION_NAME IN ('AURORA_SYNC_CONSUMER','AURORA_SYNC_EVENT',
 'AURORA_SYNC_RECEIPT','AURORA_SYNC_LINE_TOMBSTONE','AURORA_SYNC_ORDER_KEY');

SELECT TRIM(RDB$FIELD_NAME) AS FIELD_NAME
FROM RDB$RELATION_FIELDS
WHERE RDB$RELATION_NAME='OPS_LINE_ITEMS' AND RDB$FIELD_NAME='OPL_SYNC_ID';

-- Nova PROs must be globally unambiguous for the first Lykes mapping, including history.
SELECT PBNUM,COUNT(*) AS RECORDS FROM OPS_HEADER WHERE PB_TYPE='O'
GROUP BY PBNUM HAVING COUNT(*)>1;
SELECT COUNT(*) AS INVALID_PROS FROM OPS_HEADER WHERE PB_TYPE='O'
 AND (PBNUM IS NULL OR PBNUM<=0 OR PBNUM>999999999);
SELECT TRIM(PBLOCAT) AS PRO_LOCATION,TRIM(PBSUFFIX) AS SUFFIX,COUNT(*) AS RECORDS
FROM OPS_HEADER WHERE PB_TYPE='O' AND COALESCE(TRIM(PBSUFFIX),'')<>''
GROUP BY PBLOCAT,PBSUFFIX;

-- Review against configured freight keywords; charge SKUs need not be unique.
SELECT OPL_ORDER_ID,TRIM(OPL_SKU) AS SKU,COUNT(*) AS RECORDS
FROM OPS_LINE_ITEMS GROUP BY OPL_ORDER_ID,OPL_SKU HAVING COUNT(*)>1;

SELECT TRIM(PB_LOCATION) AS TERMINAL,COUNT(*) AS OPEN_ORDERS
FROM OPS_HEADER WHERE PB_TYPE='O' AND PB_DT_CANC IS NULL GROUP BY PB_LOCATION;
SELECT TRIM(OPL_KEYWORD) AS KEYWORD,TRIM(OPL_UOM) AS UOM,COUNT(*) AS LINES
FROM OPS_LINE_ITEMS GROUP BY OPL_KEYWORD,OPL_UOM;
SELECT CTS_ID,TRIM(CTS_CODE) AS STATUS_CODE FROM CT_STAT ORDER BY CTS_ID;
